const assert=require('node:assert/strict');
const {quota,tier}=require('../static/quota-mood.js');
for(const [value,expected] of [[100,'normal'],[75.01,'normal'],[75,'watch'],[50.01,'watch'],[50,'half'],[25.01,'half'],[25,'low'],[0,'low'],[null,'unknown'],[undefined,'unknown']])assert.equal(tier(value),expected);
const manual=(remaining,total,unit='token')=>({config:{source:'manual_quota',quota_remaining:remaining,quota_total:total,quota_unit:unit}});
assert.equal(quota(manual(500000,1000000)).percent,50);
assert.equal(quota(manual(0,1000000)).percent,0);
assert.equal(quota(manual(25,null,'%')).percent,25);
assert.equal(quota(manual(500000,null)),null);
assert.equal(quota(manual(500000,0)),null);
assert.equal(quota(manual(null,1000000)),null);
assert.equal(quota({config:{source:'jev',quota_total:100},reported_usage:{input_tokens:90}}),null);
assert.equal(quota({config:{source:'codex'},codex_quota:{windows:[{remaining:90,label:'5 小时'},{remaining:25,label:'每周'}]}}).percent,25);
assert.equal(quota({config:{source:'codex'},codex_quota:{windows:[{remaining:null},{remaining:'bad'}]}}),null);
assert.equal(quota({config:{source:'deepseek'},selected:{balance:'5'},estimated_tokens:500000}),null);
assert.equal(quota({config:{source:'deepseek',balance_total:20},selected:{balance:'5'},estimated_tokens:500000}).percent,25);
assert.equal(quota({config:{source:'openai',budget:20,balance_total:5},selected:{balance:'10'}}).percent,50);
assert.equal(quota({config:{source:'anthropic',budget:20},selected:{balance:'-1'}}).percent,0);
assert.equal(quota({...manual(50,100),stale:true}).stale,false);
assert.equal(quota({config:{source:'codex'},stale:true,codex_quota:{windows:[{remaining:50}]}}).stale,true);
