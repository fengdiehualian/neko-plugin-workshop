// 小小猫娘（宠物）的技能台词（第十五轮 ③）。
//
// 用户原话：
//   "给小小猫娘加技能台词，比如发动治疗的台词和发动拾取的台词，
//    还有从商店拿到免费道具的台词（她要说类似"人家给你拿到好道具啦"
//    之类的话而不是偷相关的词）各10句台词，触发的时候说。
//    并且小小猫娘拿到免费道具的时候在该道具上贴个可爱的猫爪印记。"
//
// ---- 三条设计原则 ----
//
// ① **不出现"偷"字**。用户点名了这一条，而且理由很实在：
//    "偷"是负面词，玩家看到会觉得自己在作弊。小小猫娘是帮忙的伙伴，
//    她说的话应该是"我帮你拿到啦"这种邀功的语气。
//    所以这一组台词的用词全部是"拿/捡/找/挑/顺路带"。
//
// ② 每类 10 句，**随机挑不重复**（见 pickLine）。
//    固定一句会很烦（回血可能一局触发几十次），
//    纯随机又会连着抽到同一句。所以用"洗牌袋"：
//    抽完一轮之前不会重复，抽完再重新洗。
//
// ③ 台词是**纯文本**，不碰 DOM 也不碰 canvas ——
//    由调用方决定怎么显示（现在是走 ui.toast 的气泡）。
//    这样以后想改成语音/字幕都不用动这里。
//
// 台词风格：小小猫娘是只小猫娘，说话用"人家/喵/啦"，偏软偏撒娇。
// 和主角悠怡的台词区分开（悠怡更冷静）。

