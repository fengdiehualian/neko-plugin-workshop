/**
 * "洗牌袋"取词器：抽完一轮之前不重复。
 *
 * 为什么不用 Math.random() 直接抽：
 *   回血一局能触发几十次，纯随机**必然**出现连续三次同一句的情况
 *   （生日悖论），玩家会觉得"它只会说这一句"。
 *   洗牌袋保证 10 句都用过一遍才回到开头，体感上丰富得多。
 *
 * @param {string[]} lines
 * @param {() => number} rng 0~1 的随机数（传入游戏自己的 rng 便于复现）
 * @returns {() => string} 每次调用返回一句台词
 */
export function makeLinePicker(lines, rng = Math.random) {
  let bag = [];
  return () => {
    if (!lines.length) return '';
    if (!bag.length) {
      // 重新洗牌（Fisher-Yates）
      bag = lines.slice();
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(rng() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    return bag.pop();
  };
}
