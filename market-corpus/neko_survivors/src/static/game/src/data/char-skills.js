//    test/round16-check.mjs 会断言 text 里不出现"（最终乘算）"这类字样。
//
// ② **数值分两个去处，不能混。**
//    STAT_DEFS 里的属性分两类（见 core/stats.js 的 computeStats）：
//      kind:'flat'    （maxHp / armor / hpRegen / pickupRange）
//                     → 可以走 StatSheet.addFinalMul()，最后乘一次
//      kind:'percent' （damage / attackSpeed / moveSpeed / meleeDamage …）
//                     它们的 base 是 0，`0 × 1.2` 恒等于 0 ——
//                     写进 finalMul 是一条**静默失效**的加成。
//                     → 必须走 player.charMul，在**消费点**上乘。
//
//    这就是下面 `statsFinalMul` 和 `statMul` 两个字段的分工。
//    第十六轮之前这个项目已经踩过一次同类坑（youyi 的 armor 写在 pct 里），
//    所以这次直接把两类分开命名，写错一眼能看出来。
// ============================================================

