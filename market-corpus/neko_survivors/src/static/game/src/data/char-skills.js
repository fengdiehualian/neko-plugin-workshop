// ⚠️ 两条硬规矩
// ------------------------------------------------------------
//
// ① **括号里的内容一律不进 text 字段。**
//    用户写的是"（最终乘算）""（最高累计30%概率）""（范围大概是拾取范围大小）"
//    这类**给实现者看的说明**，不是给玩家看的文案。
//    所以下面的 text 是重写过的玩家可读版本，
