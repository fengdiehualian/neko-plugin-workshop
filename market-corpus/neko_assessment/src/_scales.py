def _choices(pairs):
    """趣味/类型题：[(题干, [(选项文字, {维度: 权重})]), ...]"""
    rows = []
    for text, options in pairs:
        rows.append({
            "text": text,
            "options": [{"label": label, "weights": weights} for label, weights in options],
        })
    return rows


