def list_scales() -> list[dict]:
    """给面板用的摘要（不含题目，题目单独取，避免一次拉太多）。"""
    rows = []
    for scale in SCALES:
        rows.append({
            "id": scale["id"],
            "name": scale["name"],
            "category": scale["category"],
            "minutes": scale["minutes"],
            "kind": scale["kind"],
            "intro": scale["intro"],
            "source": scale["source"],
            "count": len(scale["items"]),
            "dims": [d["name"] for d in scale.get("dimensions", [])],
        })
    return rows


def get_scale(scale_id: str):
    for scale in SCALES:
        if scale["id"] == scale_id:
            return scale
    return None




