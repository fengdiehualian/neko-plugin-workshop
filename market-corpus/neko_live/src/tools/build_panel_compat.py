"""Generate the import-free hosted panel from its authored modules."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = ("panel_state.ts", "panel_helpers.ts", "panel_components.tsx", "panel_data_sections.tsx", "panel.tsx")
IMPORT = re.compile(r'^import\s+(?:type\s+)?[\s\S]*?\s+from\s+["\']([^"\']+)["\']\s*\n', re.MULTILINE)


def build() -> str:
    kit_names: set[str] = set()
    parts = []
    for name in MODULES:
        source = (ROOT / "ui" / name).read_text(encoding="utf-8")

        def remove_import(match: re.Match[str]) -> str:
            statement = match.group()
            if match[1] == "@neko/plugin-ui" and not statement.startswith("import type"):
                kit_names.update(item.strip() for item in statement.split("{", 1)[1].split("}", 1)[0].split(",") if item.strip())
            elif not match[1].startswith("./") and match[1] != "@neko/plugin-ui":
                raise ValueError(f"unsupported hosted import: {match[1]}")
            return ""

        source = IMPORT.sub(remove_import, source)
        source = re.sub(r'^type (PanelTranslator|DynamicLabel) = .*\n', '', source, flags=re.MULTILINE)
        source = source.replace("PluginSurfaceProps<", "CompatPluginSurfaceProps<")
        source = re.sub(r'\bexport (?=type |const |function )', '', source)
        parts.append(f"/* bundled source: ui/{name} */\n{source.strip()}\n")
    prefix = '''// Generated by tools/build_panel_compat.py; edit the modular sources.
import { NAMES } from "@neko/plugin-ui"
type CompatPluginSurfaceProps<TState = any> = {
  state?: TState
  locale?: string
  t: (key: string, params?: Record<string, any>) => string
  api: { call: (action: string, payload?: any) => Promise<any>; refresh: () => Promise<any> }
  [key: string]: any
}
type PanelTranslator = (key: string, params?: Record<string, any>) => string
type DynamicLabel = (group: string, keyPrefix: string, value: string) => string
'''.replace("NAMES", ", ".join(sorted(kit_names)))
    return prefix + "\n" + "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "ui" / "panel_compat.tsx"
    generated = build()
    if args.check:
        if target.read_text(encoding="utf-8") != generated:
            raise SystemExit("panel_compat.tsx is stale; run tools/build_panel_compat.py")
    else:
        target.write_text(generated, encoding="utf-8", newline="\n")
