def _build_minor_cards() -> list[dict]:
    cards: list[dict] = []
    card_id = 22  # 大阿卡纳 0-21 之后顺延
    for suit_code, rank, upright, reversed_, desc in _MINOR_MEANINGS:
        suit_cn, suit_en, element = _SUITS[suit_code]
        rank_cn, rank_en = _RANKS[rank - 1][1], _RANKS[rank - 1][2]
        name_cn = f"{suit_cn}{rank_cn}"
        name_en = f"{rank_en} of {suit_en}"
        cards.append({
            "id": card_id,
            "name": name_cn,
            "name_en": name_en,
            "number": str(rank),
            "arcana": "minor",
            "suit": suit_cn,
            "element": element,
            "upright": upright,
            "reversed": reversed_,
            "description": desc,
            "image": f"rws/{suit_code}{rank:02d}.jpg",
        })
        card_id += 1
    return cards


MINOR_CARDS: list[dict] = _build_minor_cards()
