def match_symbols(prompt: str) -> list[tuple[str, str, str]]:
    """从梦境描述中匹配意象，返回 [(关键词, 释义, 吉凶)]，长词优先、去重"""
    hits: list[tuple[str, str, str]] = []
    used_spans: list[tuple[int, int]] = []
    for kw in sorted(DREAM_DICT.keys(), key=len, reverse=True):
        idx = prompt.find(kw)
        if idx < 0:
            continue
        span = (idx, idx + len(kw))
        if any(not (span[1] <= s[0] or span[0] >= s[1]) for s in used_spans):
            continue
        used_spans.append(span)
        meaning, fortune = DREAM_DICT[kw]
        hits.append((kw, meaning, fortune))
    return hits[:6]


def detect_emotion(prompt: str) -> str | None:
    for emo, words in _EMOTION_WORDS.items():
        if any(w in prompt for w in words):
            return emo
    return None


def emotion_reading(prompt: str) -> tuple[str, str, str] | None:
    """若梦中含情绪词，返回 (情绪, 解读, 吉凶)，否则 None"""
    emo = detect_emotion(prompt)
    if emo is None:
        return None
    text, fortune = _EMOTION_READINGS[emo]
    return emo, text, fortune


def generic_reading(prompt: str, seed: int) -> tuple[str, str]:
    """未命中意象时的通则解读（按输入做确定性选择）"""
    emo = detect_emotion(prompt)
    if emo is not None:
        return _EMOTION_READINGS[emo]
    return _GENERIC_READINGS[seed % len(_GENERIC_READINGS)]
