def _parse_common() -> dict[str, int]:
    table: dict[str, int] = {}
    for token in _COMMON_STROKES_RAW.split():
        m = _TOKEN_RE.match(token)
        if m:
            table[m.group(1)] = int(m.group(2))
    return table


def _parse_surnames() -> dict[str, int]:
    table: dict[str, int] = {}
    for token in _SURNAMES_RAW.split():
        m = _TOKEN_RE.match(token)
        if m:
            table[m.group(1)] = int(m.group(2))
    return table


def _parse_chars() -> dict[str, tuple[int, str]]:
    """char -> (笔画, 五行)"""
    table: dict[str, tuple[int, str]] = {}
    for line in _CHARS_RAW.strip().splitlines():
        element, rest = line.split(":", 1)
        i = 0
        while i < len(rest):
            ch = rest[i]
            j = i + 1
            while j < len(rest) and rest[j].isdigit():
                j += 1
            if j > i + 1:
                table[ch] = (int(rest[i + 1:j]), element)
            i = j
    return table


