def year_pillar(year: int) -> tuple[str, str, str]:
    """返回 (干支, 生肖, 纳音五行元素)"""
    stem_idx = (year - 4) % 10
    branch_idx = (year - 4) % 12
    ganzhi = _STEMS[stem_idx] + _BRANCHES[branch_idx]
    zodiac = _ZODIAC[branch_idx]
    nayin = _NAYIN[(stem_idx % 5) * 6 + branch_idx // 2]
    element = nayin[-1]
    return ganzhi, zodiac, element


def suggest_names(surname: str, sex: str, nayin_element: str, count: int = 5) -> tuple[str, list[dict]]:
    """根据纳音五行给出补益方向并生成候选名，返回 (方向文案, 候选列表)"""
    # 补益方向：生我者为印（补生源），同类帮扶
    gen_me = [e for e, v in _GENERATE.items() if v == nayin_element][0]
    direction = f"本命纳音属{nayin_element}，宜以「{gen_me}」「{nayin_element}」二字之气补益扶助"
    seed = int(hashlib.md5(f"{surname}:{sex}:{nayin_element}".encode("utf-8")).hexdigest(), 16)
    pools: list[tuple[str, list[tuple[str, str]]]] = [
        (nayin_element, _NAME_POOL.get(nayin_element, _NAME_POOL["木"])),
        (gen_me, _NAME_POOL.get(gen_me, _NAME_POOL["水"])),
    ]
    suggestions: list[dict] = []
    seen: set[str] = set()
    i = 0
    while len(suggestions) < count and i < count * 4:
        element, pool = pools[i % 2]
        ch, meaning = pool[(seed + i * 7) % len(pool)]
        i += 1
        if ch in seen:
            continue
        seen.add(ch)
        suggestions.append({
            "name": surname + ch,
            "char": ch,
            "element": element,
            "meaning": meaning,
        })
    return direction, suggestions


def fate_score(name1: str, name2: str) -> int:
    """确定性缘分分数（40-99），同一对名字结果稳定"""
    pair = "|".join(sorted([name1.strip(), name2.strip()]))
    digest = hashlib.md5(pair.encode("utf-8")).hexdigest()
    return 40 + int(digest[:8], 16) % 60


